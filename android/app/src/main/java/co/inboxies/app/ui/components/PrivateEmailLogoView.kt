/**
 * Private Email product logo: the simplified paper plane with a half-filled shield badge
 * at the bottom right (`ic_private_email_logo`, generated by
 * `scripts/generate-logo-assets.mjs`). One colour, tinted with the in-app palette's `ink`
 * so it follows the Inboxies theme setting like iOS.
 */
@Composable
fun PrivateEmailLogoView(
    modifier: Modifier = Modifier,
    size: Dp = 24.dp,
    showTile: Boolean = false,
    alwaysLight: Boolean = false,
) {
    val colors = inboxiesColors()
    val surfaceColor = if (alwaysLight) InboxiesColors.LightSurface else colors.surface
    val lineColor = if (alwaysLight) InboxiesColors.LightLine else colors.line
    val inkColor = if (alwaysLight) InboxiesColors.LightInk else colors.ink

    if (showTile) {
        val shape = RoundedCornerShape(size * LOGO_TILE_CORNER_FRACTION)
        Box(
            modifier = modifier
                .size(size)
                .shadow(
                    elevation = 6.dp,
                    shape = shape,
                    ambientColor = Color.Black.copy(alpha = 0.08f),
                    spotColor = Color.Black.copy(alpha = 0.08f),
                )
                .clip(shape)
                .background(surfaceColor)
                .border(1.dp, lineColor.copy(alpha = 0.8f), shape),
            contentAlignment = Alignment.Center,
        ) {
            PrivateEmailMark(ink = inkColor, modifier = Modifier.size(size * 0.8f))
        }
    } else {
        PrivateEmailMark(ink = inkColor, modifier = modifier.size(size))
    }
}

@Composable
private fun PrivateEmailMark(ink: Color, modifier: Modifier) {
    Icon(
        painter = painterResource(id = R.drawable.ic_private_email_logo),
        contentDescription = "Private Email Logo",
        tint = ink,
        modifier = modifier,
    )
}
