#!/usr/bin/env node
// Regenerates extension/psl-data.js from the Public Suffix List.
//
//   node scripts/update-extension-psl.mjs            # download publicsuffix.org's list
//   node scripts/update-extension-psl.mjs list.dat   # or use a local copy
//
// The extension never fetches the list at runtime (MV3: no remote code/data on
// the matching path), so refresh this snapshot every few months and commit it.
// Unicode rules are written as punycode, the form URL.hostname gives the worker.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { domainToASCII } from "node:url";

const SOURCE = "https://publicsuffix.org/list/public_suffix_list.dat";
const out = join(dirname(fileURLToPath(import.meta.url)), "..", "extension", "psl-data.js");

const text = process.argv[2]
	? readFileSync(process.argv[2], "utf8")
	: await fetch(SOURCE).then((res) => {
			if (!res.ok) throw new Error(`${SOURCE}: HTTP ${res.status}`);
			return res.text();
		});

const sections = { icann: new Set(), private: new Set() };
let section = null;
for (const raw of text.split("\n")) {
	const line = raw.trim();
	if (line.includes("===BEGIN ICANN DOMAINS===")) section = "icann";
	else if (line.includes("===BEGIN PRIVATE DOMAINS===")) section = "private";
	else if (line.includes("===END ")) section = null;
	if (!section || !line || line.startsWith("//")) continue;
	// A rule is the first whitespace-free run on the line.
	const rule = line.split(/\s/)[0].toLowerCase();
	const prefix = rule.match(/^[!]|^(?:\*\.)+/)?.[0] ?? "";
	const ascii = domainToASCII(rule.slice(prefix.length));
	if (!ascii) throw new Error(`Cannot convert rule to punycode: ${rule}`);
	sections[section].add(prefix + ascii);
}
if (sections.icann.size < 1000 || sections.private.size < 1000) {
	throw new Error(`Suspiciously small list: ${sections.icann.size} ICANN, ${sections.private.size} private rules`);
}

const version = text.match(/^\/\/ VERSION: (.+)$/m)?.[1]?.trim() ?? "unknown";
const date = new Date().toISOString().slice(0, 10);
const pack = (set) => JSON.stringify([...set].sort().join(" "));

writeFileSync(
	out,
	`// Generated by scripts/update-extension-psl.mjs on ${date} — do not edit.
// Public Suffix List (https://publicsuffix.org), list version ${version}.
// Mozilla Public License 2.0: https://mozilla.org/MPL/2.0/
// Rules are space-separated, punycode, with the list's "*." and "!" markers.
globalThis.InboxiesPSL = {
	date: ${JSON.stringify(date)},
	version: ${JSON.stringify(version)},
	icann: ${pack(sections.icann)},
	private: ${pack(sections.private)},
};
`,
);
console.log(`wrote ${out}: ${sections.icann.size} ICANN + ${sections.private.size} private rules (list ${version})`);
